#!/usr/bin/env node
/**
 * Generate the native DSH plugin patch for @geo-radar/dsh-native.
 * Token is written only to the gitignored package patch.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const envFile = resolve(root, ".env.local");
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = /^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line.trim());
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}
const token = process.env.GEO_RADAR_TOKEN || process.argv[2];
const baseUrl = (process.env.GEO_RADAR_URL || "http://127.0.0.1:3000").replace(/\/+$/, "");
if (!token || !token.startsWith("gr_")) {
  console.error("缺少 GEO_RADAR_TOKEN（应形如 gr_...）。先运行 npm run token:create");
  process.exit(1);
}
if (!/^https?:\/\//.test(baseUrl)) {
  console.error("GEO_RADAR_URL 必须是 http(s) URL");
  process.exit(1);
}
const q = (v) => JSON.stringify(v);
const patch = `# Generated by scripts/install-dsh-native.mjs — contains a token, do not commit.
- insert:
    - id: geo-radar-native
      name: '@geo-radar/dsh-native'
      config:
        baseUrl: ${q(baseUrl)}
        token: ${q(token)}
`;
const out = resolve(root, "packages/geo-radar-dsh/cordis.patch.yml");
writeFileSync(out, patch, { encoding: "utf8", mode: 0o600 });
const profile = process.env.DSH_PROFILE || (existsSync(join(homedir(), ".dsh", "profiles", "desktop")) ? "desktop" : "web");
console.log("Native DSH patch written:", out);
console.log(`Next (run inside the package directory to avoid spaces in the absolute path):`);
console.log(`  cd "${resolve(root, "packages/geo-radar-dsh")}"`);
console.log(`  dsh plugin --profile ${profile} add .`);
console.log("Restart DSH and look for geo_search_web / geo_analyze_brand / geo_list_evidence tools.");
