#!/usr/bin/env node
/**
 * One-command Docker demo:
 *   npm run docker:up
 *
 * First run generates .env.docker with random secrets (never commit it),
 * builds the app image, starts PostgreSQL + app and waits for health.
 */
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { resolve } from "node:path";

const envFile = resolve(".env.docker");
const appPort = process.env.APP_PORT || "3000";
const postgresPort = process.env.POSTGRES_PORT || "15432";

if (!existsSync(envFile)) {
  const secret = () => randomBytes(32).toString("hex");
  const content = [
    "# Generated by npm run docker:up — do NOT commit this file.",
    `POSTGRES_PASSWORD=${randomBytes(18).toString("hex")}`,
    `AUTH_SECRET=${secret()}`,
    `CREDENTIAL_ENCRYPTION_KEY=${secret()}`,
    `CRON_SECRET=${randomBytes(24).toString("hex")}`,
    "YUANBAO_SEARCH_ENABLED=false",
    `APP_URL=http://localhost:${appPort}`,
    `APP_PORT=${appPort}`,
    `POSTGRES_PORT=${postgresPort}`,
    "",
  ].join("\n");
  writeFileSync(envFile, content, { encoding: "utf8", mode: 0o600 });
  console.log("[docker:up] generated .env.docker with random local secrets");
}

console.log("[docker:up] building and starting PostgreSQL + GEO Radar ...");
const result = spawnSync(
  "docker",
  ["compose", "--env-file", ".env.docker", "up", "-d", "--build", "--wait"],
  { stdio: "inherit", shell: process.platform === "win32" }
);

if (result.status !== 0) {
  console.error("[docker:up] failed. Try: docker compose --env-file .env.docker logs");
  process.exit(result.status ?? 1);
}

console.log(`\n[docker:up] ready: http://localhost:${appPort}`);
console.log("[docker:up] stop: npm run docker:down");
console.log("[docker:up] logs: npm run docker:logs");
